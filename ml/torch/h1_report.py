"""Hybrid H1 read-out: turns the chain's outputs (`engine-rs/scripts/h1-after-data.sh`) into a plain-text
summary and the "H1 results" markdown section, applying the preregistered rules (`d39275e`) mechanically.

    ml/.venv-hybrid/bin/python ml/torch/h1_report.py --after tmp/h1/after --summary tmp/h1/SUMMARY.txt \
        --results research_paper/v5_hybrid_results.md --runs-dir research_paper/hybrid_h1_runs

The markdown goes between `<!-- H1:AUTO:BEGIN -->` and `<!-- H1:AUTO:END -->` in the results file
(appended at the end the first time). Inputs missing because a step has not run are reported as such.
"""

from __future__ import annotations

import argparse
import glob
import json
import os
import re
import shutil

BEGIN, END = "<!-- H1:AUTO:BEGIN -->", "<!-- H1:AUTO:END -->"
FP32_GATED = ["fp32 CPU", "fp32 CUDA tf32=0"]


def load(path: str):
    try:
        return json.load(open(path))
    except (OSError, ValueError):
        return None


def yes(ok: bool | None) -> str:
    return "n/a" if ok is None else ("**pass**" if ok else "**fail**")


def ci(pair) -> str:
    return f"[{pair[0]:+.3f}, {pair[1]:+.3f}]"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default="tmp/h1", help="the chain's root (caches in <root>/cache, training in <root>/train)")
    ap.add_argument("--after", default="tmp/h1/after")
    ap.add_argument("--summary", default="tmp/h1/SUMMARY.txt")
    ap.add_argument("--results", default="research_paper/v5_hybrid_results.md")
    ap.add_argument("--runs-dir", default="research_paper/hybrid_h1_runs")
    args = ap.parse_args()
    A = args.after
    md: list[str] = []
    txt: list[str] = []
    say = lambda line="": (md.append(line), txt.append(re.sub(r"\*\*|`", "", line)))  # noqa: E731

    say(f"### H1 read-out (generated by `ml/torch/h1_report.py` from `{A}`)")
    say()

    # Corpus.
    checks = load(f"{A}/check.json") or []
    if checks:
        say("**Corpus as read** (`h1_check_v3.py`; every check passed unless listed):")
        say()
        say("| Run | Games | Records | Search records (mean legal / visited / iterations) | Teacher records (mean legal) | Problems |")
        say("|---|---:|---:|---|---|---|")
        for c in checks:
            s = (f"{c['searchRecords']:,} ({c['searchMeanLegal']:.1f} / {c['searchMeanVisited']:.1f} / {c['searchMeanIterations']:.0f})"
                 if "searchRecords" in c else "–")
            t = f"{c['teacherRecords']:,} ({c['teacherMeanLegal']:.1f})" if "teacherRecords" in c else "–"
            say(f"| `{c['run']}` | {c['games']:,} | {c['records']:,} | {s} | {t} | {'; '.join(c['problems']) or 'none'} |")
        say()
    caches = sorted(glob.glob(f"{args.root}/cache/*/meta.json"))
    if caches:
        say("**Training caches** (`h1_data.py build`; games by split train / validation / test):")
        say()
        say("| Cache | Kind | Games | Records | Policy entries | Split games |")
        say("|---|---|---:|---:|---:|---|")
        for path in caches:
            m = load(path)
            sg = m["splitGames"]
            say(f"| `{os.path.dirname(path)}` | {m['kind']} | {m['games']:,} | {m['records']:,} | {m['policyEntries']:,} | "
                f"{sg['train']:,} / {sg['val']:,} / {sg['test']:,} |")
        say()

    # Training and selection.
    arms = {k: load(f"{args.root}/train/h1-{k}.json") for k in ("A", "B")}
    if any(arms.values()):
        say("**Training** (30,000 steps, batch 512, EMA weights validated every 1,000 steps):")
        say()
        say("| Arm | Best step | Best val loss | Val visits CE / top-1 | Val teacher CE / top-1 / top-40 | Val margin R² | Minutes |")
        say("|---|---:|---:|---|---|---:|---:|")
        for k, m in arms.items():
            if not m:
                say(f"| {k} | not run | | | | | |")
                continue
            best = next(h for h in m["history"] if h["step"] == m["bestStep"])["val"]
            say(f"| {k} | {m['bestStep']:,} | {m['bestValLoss']:.4f} | {best.get('policy', float('nan')):.3f} / "
                f"{best.get('policy_top1', float('nan')):.3f} | {best.get('teacher', float('nan')):.3f} / {best.get('teacher_top1', float('nan')):.3f} / "
                f"{best.get('teacher_top40', float('nan')):.3f} | {best['marginR2']:.3f} | {m['seconds'] / 60:.0f} |")
        say()
        say("Validation loss by step:")
        say()
        steps = sorted({h["step"] for m in arms.values() if m for h in m["history"]})
        say("| Step | " + " | ".join(k for k, m in arms.items() if m) + " |")
        say("|---:|" + "---:|" * sum(1 for m in arms.values() if m))
        for st in steps:
            if st % 3000 and st != steps[-1] and not any(m and m["bestStep"] == st for m in arms.values()):
                continue
            cells = []
            for m in arms.values():
                if m:
                    h = next((x for x in m["history"] if x["step"] == st), None)
                    cells.append(f"{h['val']['loss']:.4f}" if h else "")
            say(f"| {st:,} | " + " | ".join(cells) + " |")
        say()
    sel = load(f"{A}/selection.json")
    if sel:
        say(f"**Selection:** arm {sel['selected']} (`{sel['checkpoint']}`). {sel['reason']}")
        say()

    # Offline gates.
    gates = load(f"{A}/gates.json")
    verdicts = {}
    if gates:
        t = gates["pentobiL7_teacherHead"]
        b38, b3p = t.get("3-8"), t.get("3+")
        verdicts["H1-G1"] = b38["netTop40"] >= 0.55 and b38["netTop40CI"][0] > 0.45
        verdicts["H1-G1b"] = b38["diffTop40CI"][0] > 0
        verdicts["H1-G2"] = b3p["diffLogLikCI"][0] > 0
        verdicts["H1-G3"] = gates["fuel"]["increment"] >= 0.061
        f = gates["fuel"]
        say("**Offline gates** (test split; `h1_gates.py`; bootstrap over games):")
        say()
        say("| Gate | Measured | Rule | Result |")
        say("|---|---|---|---|")
        say(f"| H1-G1 | network top-40 at own moves 3–8: {b38['netTop40']:.3f} {ci(b38['netTop40CI'])} ({b38['decisions']:,} decisions, "
            f"{b38['games']} games) | ≥ 0.55 and lower bound > 0.45 | {yes(verdicts['H1-G1'])} |")
        say(f"| H1-G1b | fitted prior {b38['priorTop40']:.3f}; network − prior {b38['diffTop40']:+.3f} {ci(b38['diffTop40CI'])} | lower bound > 0 | "
            f"{yes(verdicts['H1-G1b'])} |")
        say(f"| H1-G2 | log-likelihood own moves 3+: network {b3p['netLogLik']:.3f}, prior {b3p['priorLogLik']:.3f}, difference "
            f"{b3p['diffLogLik']:+.3f} {ci(b3p['diffLogLikCI'])} ({b3p['decisions']:,} decisions) | lower bound > 0 | {yes(verdicts['H1-G2'])} |")
        say(f"| H1-G3 | R² root value {f['r2Root']:.3f}, network {f['r2Net']:.3f}, both {f['r2Both']:.3f}; increment {f['increment']:+.3f} "
            f"[{f['ciLow']:+.3f}, {f['ciHigh']:+.3f}] ({f['positions']:,} positions, {f['games']} games) | ≥ +0.061 | {yes(verdicts['H1-G3'])} |")
        say()
        for head in ("teacher", "visits"):
            tab = gates.get(f"pentobiL7_{head}Head")
            if not tab:
                continue
            say(f"By band, level-7 test decisions, {head} head{' (gated)' if head == 'teacher' else ' (reported, not gated)'}:")
            say()
            say("| Own moves | Decisions | Net log-lik | Prior log-lik | Difference [95% CI] | Net top-40 | Prior top-40 | Difference [95% CI] |")
            say("|---|---:|---:|---:|---|---:|---:|---|")
            for band, r in tab.items():
                say(f"| {band} | {r['decisions']:,} | {r['netLogLik']:.3f} | {r['priorLogLik']:.3f} | {r['diffLogLik']:+.3f} {ci(r['diffLogLikCI'])} | "
                    f"{r['netTop40']:.3f} | {r['priorTop40']:.3f} | {r['diffTop40']:+.3f} {ci(r['diffTop40CI'])} |")
            say()
        if "fuel2" in gates:
            f2 = gates["fuel2"]
            say(f"G3 on the `v5.3-pro` test games (reported, not gated): R² root {f2['r2Root']:.3f}, network {f2['r2Net']:.3f}, "
                f"both {f2['r2Both']:.3f}, increment {f2['increment']:+.3f} [{f2['ciLow']:+.3f}, {f2['ciHigh']:+.3f}] "
                f"({f2['positions']:,} positions, {f2['games']} games).")
            say()

    # Engine interface.
    par = load(f"{A}/parity/parity.json")
    if par:
        e1 = bool(par.get("encoderEqual"))
        say(f"**H1-E1, parity** ({par['records']:,} records of `{par['run']}`, file order; reference PyTorch fp32 on the CPU):")
        say()
        say("| Path | Logits, all slots: max abs (p99.9) | Logits, legal moves: max abs (p99.9) | Utilities: max abs (p99.9) | Top-1 (teacher) |")
        say("|---|---|---|---|---:|")
        for key, r in par["onnx"].items():
            if key in FP32_GATED:
                e1 &= max(r["logitsAll"]["maxAbs"], r["logitsLegal"]["maxAbs"], r["utilities"]["maxAbs"]) <= 1e-3
            say(f"| ONNX {key}{' (gated)' if key in FP32_GATED else ''} | {r['logitsAll']['maxAbs']:.1e} ({r['logitsAll']['p999']:.1e}) | "
                f"{r['logitsLegal']['maxAbs']:.1e} ({r['logitsLegal']['p999']:.1e}) | {r['utilities']['maxAbs']:.1e} ({r['utilities']['p999']:.1e}) | "
                f"{r['top1Teacher']:.4f} |")
        for key, r in par["rust"].items():
            e1 &= r["tableEqual"] and max(r["logitsLegal"]["maxAbs"], r["utilities"]["maxAbs"]) <= 1e-3
            say(f"| engine `{key}` (gated) | – | {r['logitsLegal']['maxAbs']:.1e} ({r['logitsLegal']['p999']:.1e}) | "
                f"{r['utilities']['maxAbs']:.1e} ({r['utilities']['p999']:.1e}) | {r['top1Teacher']:.4f} |")
        say()
        say(f"Training-time encoder equals `features.Encoder.board`: {par.get('encoderEqual')}. Engine policy table equals "
            f"`policy_index.py`: {all(r['tableEqual'] for r in par['rust'].values())}. `evaluate_moves` equal to the raw session outputs "
            f"bit for bit: asserted by `examples/h1_v3_eval.rs` (the step fails otherwise).")
        verdicts["H1-E1"] = e1 and bool(par["rust"])
        say()
    lat = []
    for path in sorted(glob.glob(f"{A}/parity/rust-*.log")):
        for line in open(path):
            if "latency" in line:
                lat.append(f"{os.path.basename(path)[:-4]}: {line.strip().split('h1_v3_eval: ')[-1]}")
    if lat:
        say("**v3 call latency** (one position with its legal moves, synchronous, as the search calls it; PC otherwise idle):")
        say()
        for line in lat:
            say(f"- {line}")
        say()
    noop = f"{A}/identity-noop/log.txt"
    if os.path.exists(noop):
        text = open(noop).read()
        ok = "same" in text and "FAIL" not in text
        verdicts["H1-E3"] = ok
        line = next((l for l in text.splitlines() if "weight 0" in l), "no result line")
        say(f"**H1-E3, network at weight 0:** {line.split(' ', 2)[-1]}")
        say()

    say("**Verdicts:** " + ("; ".join(f"{k} {yes(v)}" for k, v in verdicts.items()) or "none yet") +
        ". H1-E2 (identity with the network off) passed on 2026-11-19, above.")
    say()

    # Write.
    os.makedirs(os.path.dirname(args.summary) or ".", exist_ok=True)
    open(args.summary, "w").write("\n".join(txt) + "\n")
    block = BEGIN + "\n" + "\n".join(md) + "\n" + END
    text = open(args.results).read() if os.path.exists(args.results) else ""
    if BEGIN in text and END in text:
        text = text[: text.index(BEGIN)] + block + text[text.index(END) + len(END):]
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    open(args.results, "w").write(text)
    os.makedirs(args.runs_dir, exist_ok=True)
    for path in [f"{A}/check.json", f"{A}/selection.json", f"{A}/gates.json", f"{A}/parity/parity.json", noop,
                 f"{args.root}/train/h1-A.json", f"{args.root}/train/h1-B.json", "tmp/h1/data/log.txt", f"{A}/chain.log", args.summary]:
        if os.path.exists(path):
            name = path.replace(args.root.rstrip("/") + "/", "").replace("tmp/h1/", "").replace("/", "-")
            shutil.copy(path, os.path.join(args.runs_dir, name))
    print("\n".join(txt))


if __name__ == "__main__":
    main()
