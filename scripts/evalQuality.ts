/**
 * Position-level evaluation quality, without playing a game per comparison.
 *
 * An evaluation's job is to *rank successor positions* by eventual outcome. This measures that
 * directly: sample positions from logged games, score each one with each evaluation, and correlate
 * with the margin the game actually ended on. Seconds per feature set, against ~40 seconds for a
 * 1600-game match — and unlike a match it says *where* one evaluation is less informative than
 * another.
 *
 * It also answers the question an ablation answers expensively and a fit answers slowly: does a
 * candidate feature carry information the evaluation does not already have? That is the partial
 * correlation of the feature with the outcome, controlling for the evaluation — reported below as
 * "incremental".
 *
 * Positions are drawn from games generated by *both* engines, because sampling only from one
 * engine's own play would favour that engine's evaluation: a regression is only valid over the state
 * distribution it was sampled from.
 *
 *   npm run eval-quality -- --games 60 --generators v11,v12
 */

function arg(name: string, fallback?: string): string | undefined {
  const index = process.argv.indexOf(`--${name}`);
  if (index >= 0 && process.argv[index + 1]) {
    return process.argv[index + 1];
  }
  return fallback;
}

type PhaseName = 'opening' | 'midgame' | 'endgame';

interface Row {
  phase: PhaseName;
  /** Final `score − mean(other three)` for this seat, in the game this position came from. */
  target: number;
  /** Predictors, keyed by name. */
  values: Record<string, number>;
}

/** Average-rank transform, so ties do not distort the correlation. */
function ranks(values: number[]): number[] {
  const order = values.map((v, i) => [v, i] as const).sort((a, b) => a[0] - b[0]);
  const out = new Array<number>(values.length);
  let i = 0;
  while (i < order.length) {
    let j = i;
    while (j + 1 < order.length && order[j + 1][0] === order[i][0]) {
      j += 1;
    }
    const rank = (i + j) / 2 + 1;
    for (let k = i; k <= j; k += 1) {
      out[order[k][1]] = rank;
    }
    i = j + 1;
  }
  return out;
}

function pearson(a: number[], b: number[]): number {
  const n = a.length;
  if (n < 3) {
    return Number.NaN;
  }
  let ma = 0;
  let mb = 0;
  for (let i = 0; i < n; i += 1) {
    ma += a[i];
    mb += b[i];
  }
  ma /= n;
  mb /= n;
  let num = 0;
  let da = 0;
  let db = 0;
  for (let i = 0; i < n; i += 1) {
    const x = a[i] - ma;
    const y = b[i] - mb;
    num += x * y;
    da += x * x;
    db += y * y;
  }
  const den = Math.sqrt(da * db);
  return den === 0 ? Number.NaN : num / den;
}

function spearman(a: number[], b: number[]): number {
  return pearson(ranks(a), ranks(b));
}

/**
 * Partial rank correlation of X with Y controlling for Z — "what does X add that Z does not
 * already say". Computed from the three pairwise Spearman correlations.
 */
function partial(rXY: number, rXZ: number, rYZ: number): number {
  const den = Math.sqrt((1 - rXZ * rXZ) * (1 - rYZ * rYZ));
  return den === 0 ? Number.NaN : (rXY - rXZ * rYZ) / den;
}

const context = createEvalContext();
const v12Values = new Float64Array(4);

/** Every predictor for one seat at one position. */
function predictorsFor(state: GameState, color: PlayerColor): Record<string, number> {
  const seat = SEAT_OF_COLOR[color];
  const position = toPosition(state);
  refreshContext(context, position, false);
  const phase = detectPhase(position, context, DEFAULT_BITBOARD_PARAMS, seat);
  const e = evaluate(context, position, DEFAULT_BITBOARD_PARAMS, phase);
  v12Values.set(e);

  let othersMean = 0;
  for (let s = 0; s < 4; s += 1) {
    if (s !== seat) {
      othersMean += v12Values[s];
    }
  }
  othersMean /= 3;

  // v11's evaluation is already `mine − opponent term`, so it is directly comparable in role.
  const v11 = evaluateState(state, color, true, 'v11');
  const f = extractAllFeatures(state, color, true);

  return {
    'v11 eval': v11,
    'v12 E (vs mean)': v12Values[seat] - othersMean,
    'v12 E (own only)': v12Values[seat],
    'v12 territory': context.territory.territory[seat],
    'v12 f(C)': context.cornerScore[seat],
    'v12 waste': context.waste[seat],
    'v11 uniqueLiberties': f.uniqueLiberties,
    'v11 mobility': f.mobility,
    'v11 cornerAccess': f.cornerAccess,
    'placed squares': position.placedSquares(seat),
  };
}

function phaseOf(state: GameState, color: PlayerColor): PhaseName {
  const played = 21 - state.remainingPieces[color].length;
  if (played < 5) {
    return 'opening';
  }
  return played < 15 ? 'midgame' : 'endgame';
}

async function main(): Promise<void> {
  const games = Math.max(1, Number(arg('games', '60')));
  const seedBase = Number(arg('seed-base', '6100000'));
  const policy = (arg('policy', 'greedy') ?? 'greedy') as PolicyId;
  const stride = Math.max(1, Number(arg('stride', '2')));
  const generators = (arg('generators', 'v11,v12') ?? 'v11,v12')
    .split(',')
    .map((v) => v.trim())
    .filter((v): v is AlgoVersionId => isAlgoVersionId(v));

  console.log(
    `Position-level evaluation quality — ${games} games from {${generators.join(', ')}}, ` +
      `policy ${policy}, every ${stride} plies\n`,
  );

  const rows: Row[] = [];

  for (let g = 0; g < games; g += 1) {
    const generator = generators[g % generators.length];
    resetV12();
    const pending: Array<{ phase: PhaseName; color: PlayerColor; values: Record<string, number> }> =
      [];

    const seatVersions = Object.fromEntries(
      PLAYER_COLORS.map((c) => [c, generator]),
    ) as Record<PlayerColor, AlgoVersionId>;
    const seatPolicies = Object.fromEntries(
      PLAYER_COLORS.map((c) => [c, policy]),
    ) as Record<PlayerColor, PolicyId>;

    const record = await playSeatedGame({
      hero: policy,
      opponents: policy,
      seatVersions,
      seatPolicies,
      seed: seedBase + g,
      openingRandomPlies: 8,
      openingTopK: 3,
      searchOptions: { skipWinOddsRefinement: true, lightRollouts: true },
      onPly: (state, ply) => {
        if (ply % stride !== 0) {
          return;
        }
        // Every seat is scored at this position, not just the one to move: the evaluation has to
        // rank positions for all four components of the value vector.
        for (const color of PLAYER_COLORS) {
          pending.push({ phase: phaseOf(state, color), color, values: predictorsFor(state, color) });
        }
      },
    });

    for (const entry of pending) {
      let others = 0;
      for (const c of PLAYER_COLORS) {
        if (c !== entry.color) {
          others += record.scores[c];
        }
      }
      rows.push({
        phase: entry.phase,
        target: record.scores[entry.color] - others / 3,
        values: entry.values,
      });
    }

    if ((g + 1) % 10 === 0) {
      console.log(`  ${g + 1}/${games} games — ${rows.length} rows`);
    }
  }

  const names = Object.keys(rows[0].values);
  const phases: Array<PhaseName | 'all'> = ['all', 'opening', 'midgame', 'endgame'];

  console.log('\n=== Spearman correlation with final margin ===\n');
  const header = ['predictor'.padEnd(22), ...phases.map((p) => p.padStart(9))].join('  ');
  console.log(header);
  console.log('-'.repeat(header.length));

  for (const name of names) {
    const cells = phases.map((p) => {
      const subset = p === 'all' ? rows : rows.filter((r) => r.phase === p);
      if (subset.length < 30) {
        return '     —   ';
      }
      const r = spearman(
        subset.map((s) => s.values[name]),
        subset.map((s) => s.target),
      );
      return r.toFixed(3).padStart(9);
    });
    console.log([name.padEnd(22), ...cells].join('  '));
  }

  console.log('\n=== Incremental value over v12 E, by phase ===');
  console.log('Partial rank correlation of each feature with the final margin, controlling for');
  console.log('v12 E. Near zero means v12 already knows it; large means it carries new signal.\n');

  const control = 'v12 E (vs mean)';
  const candidates = names.filter((n) => n !== control && n !== 'v12 E (own only)');
  const header2 = ['feature'.padEnd(22), ...phases.map((p) => p.padStart(9))].join('  ');
  console.log(header2);
  console.log('-'.repeat(header2.length));

  for (const name of candidates) {
    const cells = phases.map((p) => {
      const subset = p === 'all' ? rows : rows.filter((r) => r.phase === p);
      if (subset.length < 30) {
        return '     —   ';
      }
      const x = subset.map((s) => s.values[name]);
      const y = subset.map((s) => s.target);
      const z = subset.map((s) => s.values[control]);
      const value = partial(spearman(x, y), spearman(x, z), spearman(y, z));
      return value.toFixed(3).padStart(9);
    });
    console.log([name.padEnd(22), ...cells].join('  '));
  }

  console.log('\nRows per phase:');
  for (const p of phases) {
    const n = p === 'all' ? rows.length : rows.filter((r) => r.phase === p).length;
    console.log(`  ${p.padEnd(10)} ${n}`);
  }
  console.log(
    '\nNote: the four seats of one position are correlated observations, so these are diagnostics' +
      '\nfor ranking features, not significance tests.',
  );
}

void main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
